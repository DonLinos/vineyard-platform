-- Vitis Vision — εξασφαλίζει ότι κάθε κωδικός πρόσβασης (access_codes.code) είναι μοναδικός σε
-- ΟΛΑ τα οινοποιεία μαζί, όχι μόνο μέσα στο ίδιο οινοποιείο.
--
-- Γιατί χρειάζεται: η σελίδα εισόδου (access.html) ψάχνει τον κωδικό χωρίς να ξέρει ακόμα σε
-- ποιο οινοποιείο ανήκει (`select ... from access_codes where code = ...`, χωρίς winery_id).
-- Πριν, οι κωδικοί δημιουργούνταν πάντα τυχαία (6 χαρακτήρες), οπότε σύγκρουση ανάμεσα σε δύο
-- οινοποιεία ήταν σχεδόν απίθανη. Τώρα που ο admin μπορεί να ορίσει ο ίδιος τον κωδικό (π.χ.
-- κάτι απλό), αν τύχει το ίδιο string σε δύο οινοποιεία, η είσοδος θα σπάσει και για τα δύο.
--
-- Αυτό εδώ προσθέτει έναν περιορισμό μοναδικότητας στη βάση, ώστε αν προσπαθήσεις να βάλεις
-- κωδικό που υπάρχει ήδη (σε οποιοδήποτε οινοποιείο), να πάρεις καθαρό μήνυμα λάθους αμέσως
-- αντί να χαλάσει αθόρυβα η είσοδος κάποιου αργότερα.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'access_codes_code_key'
  ) then
    alter table access_codes add constraint access_codes_code_key unique (code);
  end if;
end $$;
