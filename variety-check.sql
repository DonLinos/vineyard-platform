-- αυτό διορθώνει τα ΔΕΔΟΜΕΝΑ που είναι ήδη αποθηκευμένα στον πίνακα blocks.

-- 1) Δες πρώτα ΟΛΕΣ τις διαφορετικές τιμές που υπάρχουν σήμερα στη στήλη variety,
--    μαζί με πόσα blocks έχει η καθεμία. Αν βλέπεις π.χ. και "SRH — Syrah" ΚΑΙ "SRH - Syrah"
--    (διαφορετική παύλα) ή "Mattaro" (ορθογραφικό), θα εμφανιστούν εδώ ως ξεχωριστές γραμμές.
select variety, count(*) as blocks
from blocks
group by variety
order by variety;

